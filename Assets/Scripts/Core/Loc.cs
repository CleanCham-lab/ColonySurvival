            foreach (var k in keys)
                if (r.IndexOf(k, StringComparison.Ordinal) >= 0) { r = r.Replace(k, En[k]); if (!HasKo(r)) break; }
            if (memo.Count > 4000) memo.Clear();
            memo[s] = r;
            return r;
        }

