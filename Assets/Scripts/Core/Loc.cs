            if (En.TryGetValue(s, out var e)) return e;
            if (memo.TryGetValue(s, out e)) return e;
            if (keys == null) { keys = new List<string>(En.Keys).ToArray(); Array.Sort(keys, (a, b) => b.Length.CompareTo(a.Length)); }
